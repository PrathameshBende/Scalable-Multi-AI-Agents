"""Read results/*.json and write results/SUMMARY.md (the numbers a resume may quote)."""

from __future__ import annotations

import glob
import json
import os

R = "results"


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main() -> None:
    lines = ["# Results summary", "", "Generated by `scripts/summarize.py` from the JSON files in `results/`.", ""]

    p = os.path.join(R, "retrieval.json")
    if os.path.exists(p):
        d = load(p)
        lines += [f"## Retrieval ({d['dataset']}, {d['n_queries']} queries, {d['n_docs']} docs)",
                  f"Embedder `{d['embedder']}`, LLM `{d['llm']}`. Baseline = dense. Primary metric = hit@5.", "",
                  "| strategy | hit@1 | hit@5 | hit@10 | nDCG@10 | MRR@10 | s/query |", "|---|---|---|---|---|---|---|"]
        for s, m in d["metrics"].items():
            lines.append(f"| {s} | {m['hit@1']:.3f} | {m['hit@5']:.3f} | {m['hit@10']:.3f} | "
                         f"{m['ndcg@10']:.3f} | {m['mrr@10']:.3f} | {d['seconds_per_query'][s]:.2f} |")
        lines += ["", "| vs dense | hit@5 (pts) | hit@5 (rel) | nDCG@10 (rel) | won/lost | McNemar p |",
                  "|---|---|---|---|---|---|"]
        for s, c in d["vs_baseline"].items():
            lines.append(f"| {s} | {c['hit@5_abs_points']:+.1f} | {c['hit@5_rel_pct']:+.1f}% | "
                         f"{c['ndcg@10_rel_pct']:+.1f}% | {c['queries_won_vs_baseline']}/"
                         f"{c['queries_lost_vs_baseline']} | {c['mcnemar_p_hit@5']:.3f} |")
        lines.append("")

    for p in sorted(glob.glob(os.path.join(R, "agent_*.json"))):
        d = load(p)
        s = d["summary"]
        lo, hi = s["strict_95ci"]
        lines += [f"## ReAct agent: `{d['model']}`",
                  f"- Strict success: **{s['strict_success_count']}/{s['n_runs']} = {100 * s['strict_success']:.1f}%** "
                  f"(95% CI {100 * lo:.0f}-{100 * hi:.0f}%)",
                  f"- Lenient success (any number correct): {100 * s['lenient_success']:.1f}%",
                  f"- Mean tool calls: {s['mean_tool_calls']:.1f}; runs with no tool call: {s['runs_without_any_tool_call']}; "
                  f"crashed/step limit: {s['runs_crashed_or_step_limit']}; mean {s['mean_seconds']:.1f}s per task",
                  "- By category: " + ", ".join(f"{c} {v['pass']}/{v['n']}" for c, v in s["by_category"].items()), ""]

    p = os.path.join(R, "onnx.json")
    if os.path.exists(p):
        d = load(p)
        lines += [f"## ONNX embedder (`{d['model']}`, CPU, {d['cpu_threads']} threads)", "",
                  "| variant | size MB | docs/s | hit@5 | nDCG@10 |", "|---|---|---|---|---|"]
        for n, v in d["variants"].items():
            lines.append(f"| {n} | {v['size_mb']:.1f} | {v['cpu_docs_per_sec']:.0f} | "
                         f"{v['metrics']['hit@5']:.4f} | {v['metrics']['ndcg@10']:.4f} |")
        for n, v in d["variants"].items():
            if "vs_pytorch" in v:
                c = v["vs_pytorch"]
                lines.append(f"- {n} vs PyTorch: size -{c['size_reduction_pct']:.1f}%, speed x{c['speedup_x']:.2f}, "
                             f"nDCG@10 {c['ndcg@10_rel_pct']:+.2f}% rel, hit@5 {c['hit@5_abs_points']:+.2f} pts")
        lines.append("")

    p = os.path.join(R, "gguf.json")
    if os.path.exists(p):
        d = load(p)
        lines += [f"## GGUF LLM (`{d['model']}`, llama.cpp `{d['llama_cpp_commit'][:7]}`)", "",
                  "| variant | size MB | WikiText-2 PPL | HellaSwag acc % |", "|---|---|---|---|"]
        for n, v in d["variants"].items():
            lines.append(f"| {n} | {v['size_mb']:.0f} | {v['ppl']:.3f} +/- {v['ppl_stderr']:.3f} | "
                         f"{v['hellaswag']['acc']:.2f} |")
        for n, v in d["variants"].items():
            if "vs_f16" in v:
                c = v["vs_f16"]
                lines.append(f"- {n} vs F16: size -{c['size_reduction_pct']:.1f}%, PPL +{c['ppl_increase_pct']:.2f}%, "
                             f"HellaSwag {c['hellaswag_abs_points']:+.2f} pts")
        lines.append("")

    os.makedirs(R, exist_ok=True)
    with open(os.path.join(R, "SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
